<!-- wp:paragraph {"fontSize":"medium"} -->
<p class="has-medium-font-size">CuredHosting exists because most hosting support feels like shouting into a queue. Tickets bounce between tiers, answers arrive templated, and the person who finally replies has never seen your site before. We built the opposite: a hosting service small enough to care properly, capped at twenty customer accounts, with one personal tech who knows every one of them.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">One rule we won’t break</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our guiding principle is short enough to remember: <strong>do the next right thing, no matter the cost.</strong> In practice that means telling you a plan won’t fit before you pay for it, flagging a limit you’re approaching instead of billing a surprise, and staying on the line until your site is genuinely back — even when the honest answer costs us the sale.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">What “a personal tech” means day to day</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul>
	<li>You contact a person, not a ticket system. The same person answers every time.</li>
	<li>Your setup is documented on our side, so support never starts with “please explain your configuration.”</li>
	<li>We watch the accounts we run and raise issues before they become outages, whenever we can.</li>
	<li>When something is outside our scope, we say so and help you find the right person — we don’t pocket work we can’t do well.</li>
</ul>
<!-- /wp:list -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">The infrastructure, stated plainly</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Your sites run on InMotion reseller hosting, managed with cPanel. We don’t pretend that’s a dedicated server, and we never claim resources that aren’t ours to give. What CuredHosting adds is careful configuration, honest limits, privacy-conscious tooling we wrote ourselves, and a person who stands behind the account by name.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">Why twenty accounts?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Because quality support doesn’t scale infinitely, and we’d rather be honest about that than hire a call center and pretend otherwise. Twenty accounts is the size where every customer gets real attention — and where we can keep the promise this whole site is built on: hosting with a personal tech, not a support queue.</p>
<!-- /wp:paragraph -->

