<p class="has-ink-soft-color has-text-color has-medium-font-size">This policy applies to every CuredHosting account, on every plan, including promotional ones. It exists so that each customer’s site gets the resources it needs — and no single account can crowd out its neighbors.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">1. Resources are real, and shared carefully</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>CuredHosting accounts run on responsibly managed reseller infrastructure. Each plan publishes exact limits for storage, bandwidth, databases, subdomains, email accounts, and FTP accounts. Those limits are the agreement. We never advertise “unlimited” resources, and we ask you not to design a site that assumes them.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">2. What fair use looks like</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul>
	<li>Websites that serve their own visitors and stay within their plan’s published limits.</li>
	<li>Normal use of email mailboxes for day-to-day correspondence.</li>
	<li>Reasonable scheduled tasks (crons) that run briefly and infrequently.</li>
	<li>Media that belongs to your site and is served to your site’s visitors.</li>
</ul>
<!-- /wp:list -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">3. What fair use is not</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul>
	<li>Bulk or mass email sending (newsletters to large lists belong with a proper email service, not a hosting mailbox).</li>
	<li>File hosting, image hosting, or storage-as-a-service for other people’s sites or applications.</li>
	<li>Running proxy services, mirrors, or content delivery for unrelated properties.</li>
	<li>Cryptocurrency mining or sustained maximum-CPU workloads.</li>
	<li>Automated scraping, harvesting, or attack tooling of any kind.</li>
	<li>Parked collections of domains running resource-heavy scripts without genuine visitor traffic.</li>
</ul>
<!-- /wp:list -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">4. How we respond</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>If an account approaches its limits or behaves unusually, we start with a conversation: we tell you what we observed, what it means, and what the options are (trimming, upgrading, or moving to a service that fits better). We will not silently throttle you, and we will not bill overages without your prior agreement.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>If activity threatens the stability or security of other accounts, we may take immediate protective action — including temporary suspension of the offending service — and then explain exactly what happened and what comes next. Neighbor protection is not negotiable; it is the reason twenty accounts can share infrastructure peacefully.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">5. Questions</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>If you’re planning something and aren’t sure it fits, <a href="/contact/">ask before you build</a>. We’d rather give you an honest “that needs a different kind of service” early than a painful surprise later.</p>
