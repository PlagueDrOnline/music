<p class="has-ink-soft-color has-text-color has-medium-font-size">This policy describes what may not be hosted or run on CuredHosting accounts. It complements the <a href="/fair-use/">fair-use policy</a>: fair use is about resources, this one is about conduct.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">1. Prohibited content</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul>
	<li>Content that is illegal in the jurisdictions where it is hosted and served.</li>
	<li>Malware, phishing pages, exploit kits, or anything designed to compromise visitors’ devices or accounts.</li>
	<li>Content that knowingly infringes intellectual property rights.</li>
	<li>Material that sexualizes or exploits minors — absolutely prohibited, reported, and removed immediately.</li>
</ul>
<!-- /wp:list -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">2. Prohibited activity</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul>
	<li>Sending spam or unsolicited bulk email, including from scripts installed on hosted sites.</li>
	<li>Operating botnets, attack tooling, DDoS services, or scanning other systems without authorization.</li>
	<li>Deliberately evading security controls, rate limits, or suspensions.</li>
	<li>Hosting credential lists, stolen data, or tools primarily used for account compromise.</li>
	<li>Any activity that puts other CuredHosting customers, our infrastructure provider, or the public at risk.</li>
</ul>
<!-- /wp:list -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">3. Reports and abuse contact</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>To report abuse involving a CuredHosting-hosted site, contact the support address listed on the <a href="/contact/">contact page</a> with the relevant URL and details. We investigate reports personally and respond as quickly as the situation warrants.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"fontSize":"x-large"} -->
<h2 class="wp-block-heading has-x-large-font-size">4. Enforcement</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Minor or accidental issues get a conversation first. Serious violations — malware distribution, phishing, illegal content, or deliberate abuse — result in immediate suspension and, where appropriate, removal and reporting. We always document what we did and why, and we tell you straight.</p>
<!-- /wp:paragraph -->
